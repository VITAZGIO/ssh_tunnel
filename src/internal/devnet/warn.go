package devnet

// Warn — сказать человеку то, что заметило фоновое приложение (лимит
// трафика, «файл слишком большой для буфера»): окно ПК пишет в журнал,
// телефон показывает уведомление. Источник не умеет — молчим.
func Warn(text string) {
	if w, ok := get().(interface{ Warn(string) }); ok {
		w.Warn(text)
	}
}
