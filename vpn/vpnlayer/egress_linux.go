package vpnlayer

// Выход самого сервера через другой сервер (ТЗ 10): здесь — только то, что
// отличает этот запуск от обычного устройства с полным туннелем.
//
// Панель ставит этот же ssh_tunnel_vpn_linux как для обычного клиента, но
// с переменной среды SSH_TUNNEL_ROUTE_TABLE в systemd-юните. Единственная
// разница: маршруты всего интернета (0/1, 128/1, ::/1, 8000::/1) идут не в
// таблицу main (как на устройстве — она же системная таблица маршрутов), а
// в свою таблицу. Table main и её настоящий маршрут по умолчанию панель
// оставляет как есть: без этого входящие соединения (SSH на сервер,
// панель, пользователи туннеля, meshd) после включения обхода отвечали бы
// в туннель, а не обратно тому, кто их открыл, — сервер стал бы
// недоступен снаружи.
//
// Вокруг этой таблицы панель строит свои правила ip rule (см.
// Projects/ssh_tunnel/отчёты в хранилище и docs/VPN.md): метка на ответы
// входящих соединений — в main, правило-перехватчик «остальное» — в нашу
// таблицу. Это файлы панели (src/internal/panel/egress_*.go), не этого
// пакета: здесь мы не знаем и не должны знать про их устройство — только
// кладём маршруты в указанную таблицу вместо main.

import (
	"os"
	"strconv"
)

// egressTableFromEnv — номер таблицы из SSH_TUNNEL_ROUTE_TABLE, если он
// задан и похож на таблицу (не 0, не системные 253–255, не отрицательный).
// 0 — обычный режим (маршруты в main, как на устройстве).
func egressTableFromEnv() int {
	v := os.Getenv("SSH_TUNNEL_ROUTE_TABLE")
	if v == "" {
		return 0
	}
	n, err := strconv.Atoi(v)
	if err != nil || n <= 0 || (n >= 253 && n <= 255) {
		return 0
	}
	return n
}
